#!/usr/bin/env python3
"""Generate find-me-a-skill/CATALOG.md from the repo. Stdlib only.

Sources: every skill/agent/hook (build_site.collect), site/data/meta.json
"model_effort" (site_detail.model_effort) and site/data/workflows.json
(site_workflows.load + validate), so the catalog runs the same checks as
the site build and can't drift: scripts/test_site_catalog.py fails when the
committed file differs from a fresh render.

Usage:
  python scripts/site_catalog.py          rewrite the catalog
  python scripts/site_catalog.py --check  exit 1 if it is stale
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_site  # noqa: E402
import lint  # noqa: E402
import site_detail  # noqa: E402
import site_workflows  # noqa: E402

CATALOG_PATH = ("find-me-a-skill", "CATALOG.md")
REGEN = "python scripts/site_catalog.py"


def cell(s):
    return " ".join(str(s).split()).replace("|", "\\|")


def kind_label(e):
    kind = site_workflows.kind_of(e)
    if kind == "skill" and str(e["_x"]["fm"].get("disable-model-invocation", "")).strip().lower() == "true":
        return "skill (user only)"
    return kind


def invoke(e):
    kind = site_workflows.kind_of(e)
    if kind == "agent":
        return '`Agent(subagent_type="%s")`' % e["name"]
    if kind == "hook":
        return "install: hooks/README.md"
    return "`/%s`" % e["name"]


def step_label(st, me):
    if st["kind"] == "human":
        return "you"
    d = me[st["name"]]
    pre = "/" if st["kind"] == "skill" else ""
    return "%s%s (%s, %s · %s)" % (pre, st["name"], st["kind"], d["model"], d["effort"])


def render(entries, meta, workflows):
    me = site_detail.model_effort(meta, entries)
    used = site_workflows.by_name(workflows)
    out = [
        "# Catalog",
        "",
        "Generated by `%s` from this repo's skills, agents, hooks," % REGEN,
        "`site/data/meta.json` and `site/data/workflows.json`. Don't edit by hand.",
        "",
        "Model and effort are defaults for a typical task. For a large or risky task",
        "raise effort one level first, and the model one tier only when effort is",
        "already max; for a small one lower effort first, the model only at low.",
        "Plugin installs prefix skills and agents with `krish:` (`/krish:next`).",
        "User-only skills never appear in the session's skill list, installed or",
        "not. Before calling an entry not installed, check ~/.claude/skills/<name>/",
        "and the plugin's install dir; if it is in neither, see the top README,",
        "Install section.",
        "",
        "## Entries",
        "",
        "| name | kind | model | effort | invoke | what it does | workflows |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        d = me[e["name"]]
        wfs = ", ".join(wf["name"] for wf in used.get(e["name"], [])) or "-"
        out.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            e["name"], kind_label(e), d["model"], d["effort"], invoke(e), cell(e["summary"]), wfs))
    out += ["", "## Workflows", "",
            "Each step: who acts, its model and effort, and why. `you` steps are",
            "human-in-the-loop points: nothing continues without you."]
    for wf in workflows:
        out += ["", "### %s: %s" % (wf["name"], cell(wf["title"])), ""]
        for i, st in enumerate(wf["steps"], 1):
            out.append("%d. %s: %s" % (i, step_label(st, me), cell(st["why"])))
    return "\n".join(out) + "\n"


def render_repo(root):
    entries = build_site.collect(root)
    workflows = site_workflows.validate(site_workflows.load(root), entries)
    return render(entries, site_detail.load_meta(root), workflows)


def catalog_path(root):
    return os.path.join(root, *CATALOG_PATH)


def main(argv):
    root = lint.repo_root()
    text = render_repo(root)
    path = catalog_path(root)
    if "--check" in argv:
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            print("%s is stale; run: %s" % ("/".join(CATALOG_PATH), REGEN), file=sys.stderr)
            return 1
        print("OK: %s up to date" % "/".join(CATALOG_PATH))
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("Wrote %s" % "/".join(CATALOG_PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
